// Prints the license text of every production npm dependency bundled into Flitty's UI.
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = JSON.parse(readFileSync("package.json", "utf8"));
const seen = new Map();

function packageDir(name, fromDir) {
  return dirname(require.resolve(`${name}/package.json`, { paths: [fromDir] }));
}

function visit(name, fromDir) {
  const dir = packageDir(name, fromDir);
  const manifest = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const key = `${manifest.name}@${manifest.version}`;
  if (seen.has(key)) return;
  const licenseFile = readdirSync(dir).find((file) => /^(license|licence|copying)/i.test(file));
  seen.set(key, { license: manifest.license, text: licenseFile ? readFileSync(join(dir, licenseFile), "utf8").trim() : "" });
  for (const dependency of Object.keys(manifest.dependencies ?? {})) visit(dependency, dir);
}

for (const dependency of Object.keys(root.dependencies ?? {})) visit(dependency, process.cwd());

console.log("Third-party licenses for the npm packages bundled in Flitty's interface.\nGenerated by scripts/js-licenses.mjs; do not edit by hand.\n");
for (const [key, { license, text }] of [...seen].sort()) {
  console.log("=".repeat(80) + `\n${key} (${license})\n` + "=".repeat(80) + `\n\n${text || "(no license file shipped; see the package's license field)"}\n`);
}
